export interface SpeedReadingPlacementSummary {
  recommendedLevel: number; // 1..21
  recommendedWpm: number;
  measuredWpm: number;
  readingSeconds: number;
  comprehensionPassed: boolean;
  rushedWarning: boolean;
  skillLabel: string;
}

export function evaluateSpeedReadingPlacement(params: {
  wordCount: number;
  readingTimeMs: number;
  selectedOptionIndex: number | null;
  correctOptionIndex: number;
}): SpeedReadingPlacementSummary {
  const safeWords = Math.max(10, params.wordCount);
  const readingSeconds = Number(
    Math.max(0.5, params.readingTimeMs / 1000).toFixed(1)
  );
  const rushedWarning = params.readingTimeMs < 5000;

  const effectiveSecForWpm = Math.max(8, params.readingTimeMs / 1000);
  const measuredWpm = Math.min(
    600,
    Math.max(60, Math.round((safeWords / effectiveSecForWpm) * 60))
  );

  const comprehensionPassed =
    params.selectedOptionIndex !== null &&
    params.selectedOptionIndex === params.correctOptionIndex;

  let effectiveWpm = measuredWpm;
  if (rushedWarning) {
    effectiveWpm = comprehensionPassed ? 175 : 125;
  } else if (!comprehensionPassed) {
    effectiveWpm = Math.min(150, Math.round(measuredWpm * 0.65));
  } else {
    effectiveWpm = Math.max(100, Math.min(450, measuredWpm));
  }

  const rawLevel = Math.round((effectiveWpm - 100) / 25) + 1;
  const recommendedLevel = Math.max(
    MIN_SPEED_READING_LEVEL,
    Math.min(MAX_SPEED_READING_LEVEL, rawLevel)
  );
  const recommendedWpm = getSpeedReadingWpmForLevel(recommendedLevel);

  let skillLabel = 'خواننده دقیق — شروع آرام و مطمئن';
  if (!comprehensionPassed) {
    skillLabel = 'تمرکز بر درک مطلب — شروع با سرعت متعادل';
  } else if (recommendedLevel >= 11) {
    skillLabel = 'خواننده سریع — سرعت بالا و درک کامل';
  } else if (recommendedLevel >= 7) {
    skillLabel = 'خواننده چابک — ریتم تند و تمرکز قوی';
  } else if (recommendedLevel >= 4) {
    skillLabel = 'خواننده متعادل — آماده جهش تندخوانی';
  }

  return {
    recommendedLevel,
    recommendedWpm,
    measuredWpm,
    readingSeconds,
    comprehensionPassed,
    rushedWarning,
    skillLabel,
  };
}
