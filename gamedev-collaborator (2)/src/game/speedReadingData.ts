export function getSpeedReadingDailyScript(dayNumber: number): SpeedReadingDailyScript {
  const safeDay = Number.isFinite(dayNumber) ? Math.max(1, Math.floor(dayNumber)) : 1;
  if (safeDay === 1) {
    return SPEED_READING_DAILY_SCRIPTS[1];
  }
  const mappedDay = ((safeDay - 2) % 29) + 2;
  return SPEED_READING_DAILY_SCRIPTS[mappedDay] || SPEED_READING_DAILY_SCRIPTS[2];
}

