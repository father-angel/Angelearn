export function getSpeedReadingLevelDelta(
  feedback: SpeedReadingDifficultyFeedback
): -2 | -1 | 0 | 1 | 2 {
  switch (feedback) {
    case 'very_easy':
      return 2;
    case 'easy':
      return 1;
    case 'medium':
      return 0;
    case 'hard':
      return -1;
    case 'very_hard':
      return -2;
  }
}

export function getSpeedReadingWpmForLevel(level: number): number {
  const safeLevel = Number.isFinite(level)
    ? Math.max(
        MIN_SPEED_READING_LEVEL,
        Math.min(MAX_SPEED_READING_LEVEL, Math.round(level))
      )
    : DEFAULT_INITIAL_SPEED_READING_LEVEL;
  // Level 1 = 100 WPM, Level 2 = 125 WPM, Level 3 (Default Session 1) = 150 WPM, ..., Level 21 = 600 WPM
  return 100 + (safeLevel - 1) * 25;
}

export function calculateNextSpeedReadingLevel(
  currentLevel: number,
  feedback: SpeedReadingDifficultyFeedback
): {
  previousLevel: number;
  deltaLevels: -2 | -1 | 0 | 1 | 2;
  nextLevel: number;
  previousWpm: number;
  nextWpm: number;
} {
  const safeCurrent = Number.isFinite(currentLevel)
    ? Math.max(
        MIN_SPEED_READING_LEVEL,
        Math.min(MAX_SPEED_READING_LEVEL, Math.round(currentLevel))
      )
    : DEFAULT_INITIAL_SPEED_READING_LEVEL;
  const deltaLevels = getSpeedReadingLevelDelta(feedback);
  const nextLevel = Math.max(
    MIN_SPEED_READING_LEVEL,
    Math.min(MAX_SPEED_READING_LEVEL, safeCurrent + deltaLevels)
  );
  return {
    previousLevel: safeCurrent,
    deltaLevels,
    nextLevel,
    previousWpm: getSpeedReadingWpmForLevel(safeCurrent),
    nextWpm: getSpeedReadingWpmForLevel(nextLevel),
  };
}

