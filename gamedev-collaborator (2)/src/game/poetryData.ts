export function isPoetryReadingComplete(
  secondsOnPoemPage: number,
  selectedPoetId: string | null
): boolean {
  if (!selectedPoetId) return false;
  const poetExists = FAMOUS_IRANIAN_POETS.some((p) => p.id === selectedPoetId);
  if (!poetExists) return false;
  return (
    typeof secondsOnPoemPage === 'number' &&
    Number.isFinite(secondsOnPoemPage) &&
    secondsOnPoemPage >= POETRY_MIN_READING_SECONDS
  );
}
